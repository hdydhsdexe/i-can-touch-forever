local Config=dofile('mouse_pickup/mpickup/config.lua')
local storage=dofile('tests/support/storage.lua')
local menu=dofile('tests/support/menu.lua')
local Menu=dofile('mouse_pickup/mpickup/mcm.lua')
local count,logs=0,{}
Isaac={DebugString=function(message) logs[#logs+1]=message end}
local function test(name,fn) fn(); count=count+1; print('PASS '..name) end
local function fixture(data)
    local mod,json=storage()
    if data then mod:seed(data) end
    local changes=0
    local config=Config.new(mod,json,function() changes=changes+1 end)
    config.load()
    return config,mod,json,function() return changes end
end

test('first launch uses all existing defaults without writing a save',function()
    local config,mod=fixture()
    for _,key in ipairs({'enabled','showCursor','showBox','showStatus','eidHover'}) do assert(config.get(key)==true) end
    assert(config.get('pickupButton')==1 and config.get('switchButton')==2 and config.get('language')=='auto')
    assert(mod.writes==0)
end)
test('valid partial settings preserve false values and default missing fields',function()
    local config=fixture({version=1,settings={enabled=false,showCursor=false,pickupButton=4}})
    assert(not config.get('enabled') and not config.get('showCursor') and config.get('showBox'))
    assert(config.get('pickupButton')==4 and config.get('switchButton')==2)
end)
test('invalid field types and out-of-range bindings are individually defaulted',function()
    local config=fixture({version=1,settings={enabled='false',showCursor=0,showBox=false,
        pickupButton=0,switchButton=5,language='xx',injected=true}})
    assert(config.get('enabled') and config.get('showCursor') and not config.get('showBox'))
    assert(config.get('pickupButton')==1 and config.get('switchButton')==2 and config.get('language')=='auto')
    assert(config.get('injected')==nil)
end)
test('corrupt JSON and invalid top-level payloads fall back and log without rewriting data',function()
    local config,mod=fixture()
    mod:SaveData('{broken')
    local before=#logs; config.load()
    assert(#logs==before+1 and config.get('enabled') and mod:LoadData()=='{broken')
    for _,data in ipairs({false,42,'text',{}, {version=2,settings={enabled=false}}, {version=1,settings=false}}) do
        mod:seed(data); before=#logs; config.load(); assert(#logs==before+1 and config.get('enabled'))
    end
end)
test('duplicate saved bindings reset both keys to defaults',function()
    for button=1,4 do
        local config=fixture({version=1,settings={pickupButton=button,switchButton=button,showStatus=false}})
        assert(config.get('pickupButton')==1 and config.get('switchButton')==2 and not config.get('showStatus'))
    end
end)
test('conflicting edits swap both bindings in one write and one change notification',function()
    local config,mod,json,changes=fixture()
    assert(config.set('pickupButton',2))
    assert(config.get('pickupButton')==2 and config.get('switchButton')==1 and mod.writes==1 and changes()==2)
    local data=json.decode(mod:LoadData())
    assert(data.version==1 and data.settings.pickupButton==2 and data.settings.switchButton==1)
    assert(config.set('switchButton',2))
    assert(config.get('pickupButton')==1 and config.get('switchButton')==2 and mod.writes==2 and changes()==3)
end)
test('invalid and unchanged edits neither write nor notify',function()
    local config,mod,_,changes=fixture()
    for _,case in ipairs({{'enabled','no'},{'pickupButton',0},{'pickupButton',1.5},
        {'switchButton',5},{'language','de'},{'unknown',true},{'enabled',true}}) do
        assert(not config.set(case[1],case[2]))
    end
    assert(mod.writes==0 and changes()==1)
end)
test('edits survive new config instances and remain isolated by engine save slot',function()
    local config,mod,json=fixture()
    config.set('enabled',false); config.set('pickupButton',4); config.set('language','zh')
    local restarted=Config.new(mod,json); restarted.load()
    assert(not restarted.get('enabled') and restarted.get('pickupButton')==4 and restarted.get('language')=='zh')
    mod:slot(2); restarted.load(); assert(restarted.get('enabled') and restarted.get('pickupButton')==1)
    restarted.set('showBox',false)
    mod:slot(1); restarted.load(); assert(not restarted.get('enabled') and restarted.get('showBox'))
    mod:slot(3); restarted.load(); assert(restarted.get('enabled') and restarted.get('showBox'))
end)
test('menu can load late, ignores incomplete APIs and registers each instance once',function()
    local config=fixture(); local adapter=Menu.new(config)
    ModConfigMenu=nil; adapter.update()
    ModConfigMenu={AddSetting=function() error('incomplete API must not be invoked') end}; adapter.update()
    ModConfigMenu.OptionType=true; adapter.update()
    local first=menu(true); ModConfigMenu=first; adapter.update(); adapter.update()
    assert(first.registrations==8 and first.removals==2 and first.name=='I can touch forever!')
    local second=menu(false); ModConfigMenu=second; adapter.update(); assert(second.registrations==8)
    ModConfigMenu=first; adapter.update(); assert(first.registrations==8)
    adapter.remove(); assert(#first.options==0); adapter.update(); assert(#first.options==8)
    local reloaded=Menu.new(config); reloaded.update(); assert(#first.options==8)
end)
test('Chinese menu switches dynamically between auto, English and Chinese without duplicate rows',function()
    local config=fixture(); ModConfigMenu=menu(true); local adapter=Menu.new(config); adapter.update()
    local options=ModConfigMenu.options
    assert(options[1].Display()=='启用鼠标拾取: 开' and options[8].CurrentSetting()==1)
    options[8].OnChange(3); adapter.update()
    assert(options[1].Display()=='Enable Mouse Pickup: On' and ModConfigMenu.name=='I can touch forever!')
    assert(options[1].Info()[1]:find('Enable mouse pickup',1,true))
    options[8].OnChange(2); adapter.update()
    assert(options[1].Display()=='启用鼠标拾取: 开' and ModConfigMenu.name=='I can touch forever!')
    options[8].OnChange(1); adapter.update(); assert(config.get('language')=='auto' and #options==8)
end)
test('Pure stays English with a fixed language row while preserving the Chinese preference',function()
    local config,mod=fixture(); config.set('language','zh')
    ModConfigMenu=menu(false); Menu.new(config).update()
    local options=ModConfigMenu.options
    assert(options[1].Display()=='Enable Mouse Pickup: On')
    assert(options[8].Minimum==3 and options[8].Maximum==3 and options[8].CurrentSetting()==3)
    assert(options[8].Display()=='Menu language: English (Pure)')
    assert(options[8].Info()[1]:find('requires Mod Config Menu Chinese',1,true))
    local before=mod.writes; options[8].OnChange(3)
    assert(config.get('language')=='zh' and mod.writes==before)
end)
test('menu controls read actual values, save immediately and swap bindings atomically',function()
    local config,mod=fixture(); ModConfigMenu=menu(false); Menu.new(config).update()
    local options=ModConfigMenu.options
    for _,i in ipairs({1,4,5,6,7}) do
        assert(options[i].Type==ModConfigMenu.OptionType.BOOLEAN and options[i].CurrentSetting())
        options[i].OnChange(false); assert(not options[i].CurrentSetting())
    end
    assert(mod.writes==5)
    options[2].OnChange(2)
    assert(options[2].CurrentSetting()==2 and options[3].CurrentSetting()==1 and mod.writes==6)
    options[2].OnChange(4); assert(options[2].Display()=='Pickup button: M5')
    local before=mod.writes; options[2].OnChange(0); assert(mod.writes==before)
    assert(not config.get('enabled') and not config.get('eidHover'))
end)
ModConfigMenu=nil
print(count..' configuration/menu tests passed (simulated storage and MCM APIs)')
